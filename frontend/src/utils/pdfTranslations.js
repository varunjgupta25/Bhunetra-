// Map alias / fallback languages for other 8th Schedule languages so everything resolves gracefully
const SCRIPT_ALIASES = {
  sd: 'hi',    // Sindhi -> Devanagari Hindi translation default
  ks: 'ur',    // Kashmiri -> Urdu translation default
  doi: 'hi',   // Dogri -> Hindi translation default
  mni: 'bn',   // Manipuri -> Bengali translation default
  sat: 'hi',   // Santali -> Hindi translation default
  brx: 'hi',   // Bodo -> Hindi translation default
}

/**
 * Safe translation lookup with layered fallback:
 * lang -> script alias -> English.
 *
 * @param {string} key - Translation key
 * @param {string} lang - Language code (e.g. 'mr', 'hi', 'gu', 'ta')
 * @returns {string} Translated string or fallback
 */
export function t(key, lang = 'en') {
  const effectiveLang = TRANSLATIONS[lang] ? lang : (SCRIPT_ALIASES[lang] || 'en')
  const langMap = TRANSLATIONS[effectiveLang] || TRANSLATIONS['en']
  const value = langMap?.[key]

  if (value !== undefined) return value

  // Fallback to English
  const enValue = TRANSLATIONS['en']?.[key]
  if (enValue !== undefined) return enValue

  return key
}

export function requiresUnicodeFont(lang) {
  return ['mr', 'hi', 'sa', 'ne', 'kok', 'doi', 'mai', 'brx', 'mni'].includes(lang)
}

export function requiresExtendedUnicodeFont(lang) {
  return ['bn', 'gu', 'ta', 'te', 'kn', 'ml', 'pa', 'or', 'as', 'ur', 'ks', 'sd', 'sat'].includes(lang)
}

